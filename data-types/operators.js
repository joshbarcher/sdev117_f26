
//powers of 2
console.log(2 ** 0);  //1
console.log(2 ** 1);  //2
console.log(2 ** 2);  //4
console.log(2 ** 3);  //8
console.log(2 ** 4);  //16
console.log(2 ** 5);  //32
console.log(2 ** 6);  //64
console.log(2 ** 7);  //128
console.log(2 ** 8);  //256

console.log(Math.pow(3, 4));

//short hand operators
let num = 42;
console.log(`Num = ${num}`);

num += 3; //short for num = num + 3
console.log(`Num = ${num}`);

num -= 10; //short for num = num - 10
console.log(`Num = ${num}`);

num /= 2; //short for num = num / 2
console.log(`Num = ${num}`);

